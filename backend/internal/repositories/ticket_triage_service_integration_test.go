// These tests run TicketTriageService against the real repositories and the
// tickordo_test database. They live in this package so they share its
// TestMain: a second package touching the same database would run in
// parallel with these tests under "go test ./..." and race on resetSchema
// and the dashboard tests' table cleanup.

// fakeAnalyzer stands in for the OpenAI analyzer so no real API call is made.
// It records the ticket it received and returns triage and err.
type fakeAnalyzer struct {
	triage *models.TicketTriage
	err    error

	calls     int
	gotTicket *models.Ticket
}

func (f *fakeAnalyzer) Analyze(ctx context.Context, ticket *models.Ticket) (*models.TicketTriage, error) {
	f.calls++
	f.gotTicket = ticket
	return f.triage, f.err
}

type triageServiceFixture struct {
	db       *pgxpool.Pool
	tickets  *repositories.TicketRepository
	triages  *repositories.TicketTriageRepository
	analyzer *fakeAnalyzer
	service  *services.TicketTriageService
}

func newTriageServiceFixture(t *testing.T, analyzer *fakeAnalyzer) *triageServiceFixture {
	t.Helper()

	db := repositories.RequireTestDB(t)
	tickets := repositories.NewTicketRepository(db)
	triages := repositories.NewTicketTriageRepository(db)

	return &triageServiceFixture{
		db:       db,
		tickets:  tickets,
		triages:  triages,
		analyzer: analyzer,
		service:  services.NewTicketTriageService(tickets, triages, analyzer),
	}
}

// createTicket inserts an open ticket and, when the test finishes, deletes
// its triages and then the ticket itself. Triage IDs are generated by the
// service, so they are removed by ticket_id; the order matters because
// ticket_triages references tickets without ON DELETE CASCADE.
func (f *triageServiceFixture) createTicket(t *testing.T, title string) *models.Ticket {
	t.Helper()

	ticket := &models.Ticket{
		ID:          uuid.New(),
		Title:       title,
		Description: "Description for " + title,
		Status:      "open",
	}

	if err := f.tickets.Create(context.Background(), ticket); err != nil {
		t.Fatalf("failed to create ticket: %v", err)
	}

	t.Cleanup(func() {
		ctx := context.Background()

		if _, err := f.db.Exec(ctx, "DELETE FROM ticket_triages WHERE ticket_id = $1", ticket.ID); err != nil {
			t.Errorf("failed to delete test triages: %v", err)
		}

		if _, err := f.db.Exec(ctx, "DELETE FROM tickets WHERE id = $1", ticket.ID); err != nil {
			t.Errorf("failed to delete test ticket: %v", err)
		}
	})

	return ticket
}

func (f *triageServiceFixture) countTriages(t *testing.T, ticketID uuid.UUID) int {
	t.Helper()

	var count int
	if err := f.db.QueryRow(context.Background(), "SELECT COUNT(*) FROM ticket_triages WHERE ticket_id = $1", ticketID).Scan(&count); err != nil {
		t.Fatalf("failed to count triages: %v", err)
	}

	return count
}

// databaseNow returns PostgreSQL's NOW() in its own transaction, so it can be
// used as a bound for timestamps written by later or earlier statements.
func (f *triageServiceFixture) databaseNow(t *testing.T) time.Time {
	t.Helper()

	var now time.Time
	if err := f.db.QueryRow(context.Background(), "SELECT NOW()").Scan(&now); err != nil {
		t.Fatalf("failed to read database time: %v", err)
	}

	return now
}

// assertTicketUnchanged checks that analyzing a ticket did not modify it.
func (f *triageServiceFixture) assertTicketUnchanged(t *testing.T, want *models.Ticket) {
	t.Helper()

	got, err := f.tickets.GetByID(context.Background(), want.ID)
	if err != nil {
		t.Fatalf("failed to reload ticket: %v", err)
	}

	if got.Status != want.Status {
		t.Errorf("expected status %q, got %q", want.Status, got.Status)
	}

	if !got.UpdatedAt.Equal(want.UpdatedAt) {
		t.Errorf("expected updated_at %v, got %v", want.UpdatedAt, got.UpdatedAt)
	}
}

func TestTicketTriageServiceAnalyzeTicketPersistsAnalyzerResult(t *testing.T) {
	analyzer := &fakeAnalyzer{}
	f := newTriageServiceFixture(t, analyzer)
	ctx := context.Background()

	ticket := f.createTicket(t, "Login fails after password reset")

	analyzer.triage = &models.TicketTriage{
		Category:        "authentication",
		Priority:        "high",
		Sentiment:       "frustrated",
		SuggestedTeam:   "identity",
		Summary:         "User cannot sign in after resetting the password.",
		SuggestedAction: "Check the password reset token flow.",
		Confidence:      0.87,
		Model:           "fake-model",
	}

	got, err := f.service.AnalyzeTicket(ctx, ticket.ID)
	if err != nil {
		t.Fatalf("expected no error, got %v", err)
	}

	// The analyzer must receive the ticket as PostgreSQL returned it.
	if analyzer.calls != 1 {
		t.Fatalf("expected 1 analyzer call, got %d", analyzer.calls)
	}

	gotTicket := analyzer.gotTicket
	if gotTicket.ID != ticket.ID || gotTicket.Title != ticket.Title || gotTicket.Description != ticket.Description || gotTicket.Status != "open" {
		t.Errorf("expected analyzer to receive ticket %+v, got %+v", ticket, gotTicket)
	}

	if !gotTicket.CreatedAt.Equal(ticket.CreatedAt) || !gotTicket.UpdatedAt.Equal(ticket.UpdatedAt) {
		t.Errorf("expected analyzer ticket timestamps %v/%v, got %v/%v", ticket.CreatedAt, ticket.UpdatedAt, gotTicket.CreatedAt, gotTicket.UpdatedAt)
	}

	if gotTicket.LatestTriageCategory != nil || gotTicket.LatestTriagePriority != nil {
		t.Errorf("expected analyzer ticket without previous triage, got category=%v priority=%v", gotTicket.LatestTriageCategory, gotTicket.LatestTriagePriority)
	}

	history, err := f.triages.ListByTicketID(ctx, ticket.ID)
	if err != nil {
		t.Fatalf("failed to list triages: %v", err)
	}

	if len(history) != 1 {
		t.Fatalf("expected 1 saved triage, got %d", len(history))
	}

	saved := history[0]

	// Every field read back from PostgreSQL must match what the service returned.
	want := models.TicketTriage{
		ID:              got.ID,
		TicketID:        ticket.ID,
		Category:        "authentication",
		Priority:        "high",
		Sentiment:       "frustrated",
		SuggestedTeam:   "identity",
		Summary:         "User cannot sign in after resetting the password.",
		SuggestedAction: "Check the password reset token flow.",
		Confidence:      0.87,
		Model:           "fake-model",
		CreatedAt:       got.CreatedAt,
	}

	for _, triage := range []struct {
		name string
		got  *models.TicketTriage
	}{
		{name: "returned", got: got},
		{name: "saved", got: saved},
	} {
		if triage.got.ID != want.ID ||
			triage.got.TicketID != want.TicketID ||
			triage.got.Category != want.Category ||
			triage.got.Priority != want.Priority ||
			triage.got.Sentiment != want.Sentiment ||
			triage.got.SuggestedTeam != want.SuggestedTeam ||
			triage.got.Summary != want.Summary ||
			triage.got.SuggestedAction != want.SuggestedAction ||
			triage.got.Confidence != want.Confidence ||
			triage.got.Model != want.Model ||
			!triage.got.CreatedAt.Equal(want.CreatedAt) {
			t.Errorf("expected %s triage %+v, got %+v", triage.name, want, *triage.got)
		}
	}

	// The ticket now reports the new triage as its latest one.
	reloaded, err := f.tickets.GetByID(ctx, ticket.ID)
	if err != nil {
		t.Fatalf("failed to reload ticket: %v", err)
	}

	if reloaded.LatestTriageCategory == nil || *reloaded.LatestTriageCategory != want.Category {
		t.Errorf("expected latest triage category %q, got %v", want.Category, reloaded.LatestTriageCategory)
	}

	if reloaded.LatestTriagePriority == nil || *reloaded.LatestTriagePriority != want.Priority {
		t.Errorf("expected latest triage priority %q, got %v", want.Priority, reloaded.LatestTriagePriority)
	}
}

func TestTicketTriageServiceAnalyzeTicketAssignsIDsAndDatabaseTimestamp(t *testing.T) {
	analyzer := &fakeAnalyzer{}
	f := newTriageServiceFixture(t, analyzer)
	ctx := context.Background()

	ticket := f.createTicket(t, "Analyzed ticket")
	otherTicket := f.createTicket(t, "Ticket the analyzer points at")

	// The analyzer tries to choose the ID, the ticket and the timestamp; the
	// service and PostgreSQL must override all three.
	analyzerID := uuid.MustParse("00000000-0000-0000-0000-0000000000aa")
	analyzerCreatedAt := time.Date(2000, time.January, 1, 0, 0, 0, 0, time.UTC)

	analyzer.triage = &models.TicketTriage{
		ID:              analyzerID,
		TicketID:        otherTicket.ID,
		Category:        "billing",
		Priority:        "medium",
		Sentiment:       "neutral",
		SuggestedTeam:   "finance",
		Summary:         "Invoice question.",
		SuggestedAction: "Forward to finance.",
		Confidence:      0.5,
		Model:           "fake-model",
		CreatedAt:       analyzerCreatedAt,
	}

	before := f.databaseNow(t)

	got, err := f.service.AnalyzeTicket(ctx, ticket.ID)
	if err != nil {
		t.Fatalf("expected no error, got %v", err)
	}

	after := f.databaseNow(t)

	if got.ID == uuid.Nil || got.ID == analyzerID {
		t.Errorf("expected a new triage ID, got %s", got.ID)
	}

	if got.TicketID != ticket.ID {
		t.Errorf("expected returned ticket ID %s, got %s", ticket.ID, got.TicketID)
	}

	saved, err := f.triages.GetLatestByTicketID(ctx, ticket.ID)
	if err != nil {
		t.Fatalf("failed to load saved triage: %v", err)
	}

	if saved.ID != got.ID {
		t.Errorf("expected saved triage ID %s, got %s", got.ID, saved.ID)
	}

	// created_at comes from the column default, returned by Create.
	if saved.CreatedAt.Before(before) || saved.CreatedAt.After(after) {
		t.Errorf("expected created_at between %v and %v, got %v", before, after, saved.CreatedAt)
	}

	if !got.CreatedAt.Equal(saved.CreatedAt) {
		t.Errorf("expected returned created_at %v, got %v", saved.CreatedAt, got.CreatedAt)
	}

	if count := f.countTriages(t, ticket.ID); count != 1 {
		t.Errorf("expected 1 triage for the analyzed ticket, got %d", count)
	}

	if count := f.countTriages(t, otherTicket.ID); count != 0 {
		t.Errorf("expected no triage for the analyzer's ticket, got %d", count)
	}

	var analyzerIDRows int
	if err := f.db.QueryRow(ctx, "SELECT COUNT(*) FROM ticket_triages WHERE id = $1", analyzerID).Scan(&analyzerIDRows); err != nil {
		t.Fatalf("failed to count triages: %v", err)
	}

	if analyzerIDRows != 0 {
		t.Errorf("expected no triage saved with the analyzer's ID, got %d", analyzerIDRows)
	}

	// Analysis only adds a triage; the ticket itself is not modified.
	f.assertTicketUnchanged(t, ticket)
}

func TestTicketTriageServiceAnalyzeTicketReturnsNotFoundForUnknownTicket(t *testing.T) {
	analyzer := &fakeAnalyzer{triage: &models.TicketTriage{}}
	f := newTriageServiceFixture(t, analyzer)

	unknownID := uuid.New()

	got, err := f.service.AnalyzeTicket(context.Background(), unknownID)

	if !errors.Is(err, repositories.ErrTicketNotFound) {
		t.Fatalf("expected ErrTicketNotFound, got %v", err)
	}

	if got != nil {
		t.Errorf("expected nil triage, got %+v", got)
	}

	// No analysis (and no OpenAI cost) for a ticket that does not exist.
	if analyzer.calls != 0 {
		t.Errorf("expected 0 analyzer calls, got %d", analyzer.calls)
	}

	if count := f.countTriages(t, unknownID); count != 0 {
		t.Errorf("expected no triage to be saved, got %d", count)
	}
}

func TestTicketTriageServiceAnalyzeTicketDoesNotPersistOnAnalyzerError(t *testing.T) {
	analyzerErr := errors.New("analyzer unavailable")
	analyzer := &fakeAnalyzer{err: analyzerErr}
	f := newTriageServiceFixture(t, analyzer)

	ticket := f.createTicket(t, "Analyzer fails")

	got, err := f.service.AnalyzeTicket(context.Background(), ticket.ID)

	if !errors.Is(err, analyzerErr) {
		t.Fatalf("expected analyzer error, got %v", err)
	}

	if got != nil {
		t.Errorf("expected nil triage, got %+v", got)
	}

	if analyzer.calls != 1 {
		t.Errorf("expected 1 analyzer call, got %d", analyzer.calls)
	}

	if count := f.countTriages(t, ticket.ID); count != 0 {
		t.Errorf("expected no triage to be saved, got %d", count)
	}

	f.assertTicketUnchanged(t, ticket)
}

func TestTicketTriageServiceAnalyzeTicketDoesNotPersistRejectedTriage(t *testing.T) {
	analyzer := &fakeAnalyzer{}
	f := newTriageServiceFixture(t, analyzer)

	ticket := f.createTicket(t, "Analyzer returns an oversized category")

	// ticket_triages.category is VARCHAR(50), so PostgreSQL rejects the row.
	analyzer.triage = &models.TicketTriage{
		Category:        strings.Repeat("c", 51),
		Priority:        "low",
		Sentiment:       "neutral",
		SuggestedTeam:   "support",
		Summary:         "Test summary",
		SuggestedAction: "Test action",
		Confidence:      0.9,
		Model:           "fake-model",
	}

	got, err := f.service.AnalyzeTicket(context.Background(), ticket.ID)

	var pgErr *pgconn.PgError
	if !errors.As(err, &pgErr) {
		t.Fatalf("expected a PostgreSQL error, got %v", err)
	}

	// 22001 is string_data_right_truncation.
	if pgErr.Code != "22001" {
		t.Errorf("expected SQLSTATE 22001, got %s", pgErr.Code)
	}

	if got != nil {
		t.Errorf("expected nil triage, got %+v", got)
	}

	if count := f.countTriages(t, ticket.ID); count != 0 {
		t.Errorf("expected no triage to be saved, got %d", count)
	}

	f.assertTicketUnchanged(t, ticket)
}
